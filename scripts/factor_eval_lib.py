#!/usr/bin/env python
"""
factor_eval_lib.py

Core library for Phase-2 factor evaluation.

Responsibilities:
- Load factor_plan JSON generated by factor_plan_lib.
- Build an evaluation configuration (root paths, mode, workers).
- For each factor in the plan, run compute + eval / eval-only / dryrun.
- Write factor_eval JSON artefacts and return an in-memory summary.

This module is intentionally deterministic and idempotent:
given the same inputs (root, plan, mode, overwrite flags),
it will always produce the same outputs or raise explicit errors.

Domain-specific pieces (factor calculation and WF metrics) are delegated
to small, overridable functions. By default, these raise NotImplementedError
so that you do not accidentally trust placeholder statistics.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional, TypedDict, Literal

import pandas as pd


# ---------------------------------------------------------------------------
# Typed dictionaries matching factor_plan schema
# ---------------------------------------------------------------------------


class FactorPlanItem(TypedDict):
    factor_id: str
    category: str
    data_freq: str
    decided_action: str
    enabled: bool
    engine: str
    extras: Dict[str, Any]
    gate_rules: Dict[str, Any]
    reasons: List[str]
    status: Optional[str]
    universe: str
    wf_windows: List[int]


class FactorPlan(TypedDict):
    as_of_date: str
    engine_kind: str
    generated_at: str
    items: List[FactorPlanItem]
    metadata: Dict[str, Any]
    profile: str
    summary: Dict[str, Any]
    wf_windows: List[int]


# ---------------------------------------------------------------------------
# Configuration objects
# ---------------------------------------------------------------------------


@dataclass
class FactorEvalConfig:
    root: Path
    as_of_date: date
    profile: str
    engine_kind: str
    wf_windows: List[int]
    mode: Literal["compute+eval", "evalonly", "dryrun"]
    max_workers: Optional[int] = None
    overwrite: bool = False


@dataclass
class FactorEvalItemResult:
    factor_id: str
    engine: str
    category: str
    decided_action: str
    status: str
    reason: Optional[str]
    metrics_path: Optional[str]
    factor_path: Optional[str]
    metrics: Optional[Dict[str, Any]]


@dataclass
class FactorEvalSummary:
    as_of_date: str
    profile: str
    engine_kind: str
    total: int
    compute_and_eval: int
    eval_only: int
    skipped: int
    failed: int


@dataclass
class FactorEvalRunResult:
    config: FactorEvalConfig
    items: List[FactorEvalItemResult]
    summary: FactorEvalSummary


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _parse_date(value: str) -> date:
    from datetime import datetime as _dt

    try:
        return _dt.strptime(value, "%Y-%m-%d").date()
    except ValueError as exc:
        raise ValueError(f"Invalid as_of_date: {value!r}, expected YYYY-MM-DD") from exc


def load_factor_plan(path: str | Path) -> FactorPlan:
    """
    Load a factor_plan JSON file generated by factor_plan_lib.

    The function performs light validation on required keys but deliberately
    does not enforce full schema to keep it forward-compatible.
    """
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(f"factor_plan JSON not found: {p}")
    with p.open("r", encoding="utf-8") as f:
        data = json.load(f)

    # Basic shape checks
    for key in ("as_of_date", "engine_kind", "items", "profile", "summary"):
        if key not in data:
            raise ValueError(f"factor_plan JSON missing required key: {key!r}")

    if not isinstance(data["items"], list):
        raise ValueError("factor_plan['items'] must be a list")

    return data  # type: ignore[return-value]


def build_eval_config(
    root: str | Path,
    plan: FactorPlan,
    mode: Literal["compute+eval", "evalonly", "dryrun"] = "compute+eval",
    max_workers: Optional[int] = None,
    overwrite: bool = False,
) -> FactorEvalConfig:
    """
    Build a FactorEvalConfig from root path and factor_plan.
    """
    root_path = Path(root).resolve()
    as_of = _parse_date(plan["as_of_date"])
    engine_kind = plan.get("engine_kind", "classic")
    profile = plan.get("profile", "dev")
    wf_windows = plan.get("wf_windows") or plan["summary"].get("wf_windows") or []

    return FactorEvalConfig(
        root=root_path,
        as_of_date=as_of,
        profile=profile,
        engine_kind=engine_kind,
        wf_windows=[int(w) for w in wf_windows],
        mode=mode,
        max_workers=max_workers,
        overwrite=overwrite,
    )


# ---------------------------------------------------------------------------
# Core pipeline
# ---------------------------------------------------------------------------


def run_factor_eval_for_plan(
    plan: FactorPlan,
    config: FactorEvalConfig,
) -> FactorEvalRunResult:
    """
    Execute factor evaluation for all items in the plan, according to config.mode.

    This is the high-level orchestration entrypoint used by scripts/factor_eval.py.
    """
    items: List[FactorEvalItemResult] = []

    for item in plan["items"]:
        result = _evaluate_single_item(item, plan=plan, config=config)
        items.append(result)

    summary = _summarise_results(plan=plan, config=config, results=items)
    return FactorEvalRunResult(config=config, items=items, summary=summary)


def _evaluate_single_item(
    item: FactorPlanItem,
    *,
    plan: FactorPlan,
    config: FactorEvalConfig,
) -> FactorEvalItemResult:
    factor_id = item["factor_id"]
    engine = item["engine"]
    decided_action = item.get("decided_action", "")
    category = item.get("category", "")
    status = "pending"
    reason: Optional[str] = None
    metrics_path: Optional[str] = None
    factor_path: Optional[str] = None
    metrics: Optional[Dict[str, Any]] = None

    try:
        # 決定要做什麼：global mode + per-factor decided_action
        if config.mode == "dryrun":
            status = "skipped"
            reason = "global mode=dryrun"
            return FactorEvalItemResult(
                factor_id=factor_id,
                engine=engine,
                category=category,
                decided_action=decided_action,
                status=status,
                reason=reason,
                metrics_path=None,
                factor_path=None,
                metrics=None,
            )

        if decided_action == "skip" or not item.get("enabled", False):
            status = "skipped"
            reason = (
                f"decided_action={decided_action!r}, enabled={item.get('enabled')!r}"
            )
            return FactorEvalItemResult(
                factor_id=factor_id,
                engine=engine,
                category=category,
                decided_action=decided_action,
                status=status,
                reason=reason,
                metrics_path=None,
                factor_path=None,
                metrics=None,
            )

        # Path 規則
        factor_path = _factor_timeseries_output_path(
            root=config.root,
            factor_id=factor_id,
            as_of=config.as_of_date,
        )
        metrics_path_obj = _factor_eval_output_path(
            root=config.root,
            factor_id=factor_id,
            as_of=config.as_of_date,
        )

        # Compute / Load factor 時間序列
        if config.mode == "compute+eval":
            df = compute_factor_timeseries(
                factor_id=factor_id,
                item=item,
                plan=plan,
                config=config,
            )
            _write_factor_timeseries(df, factor_path, overwrite=config.overwrite)
        elif config.mode == "evalonly":
            df = load_factor_timeseries(factor_path)
        else:  # 不該到這裡，Literal 已限制
            raise ValueError(f"Unsupported mode {config.mode!r}")

        # 計算 WF 指標
        metrics = compute_factor_metrics(
            factor_id=factor_id,
            df=df,
            item=item,
            plan=plan,
            config=config,
        )

        # 寫出 factor_eval JSON
        _write_factor_eval_json(
            path=metrics_path_obj,
            factor_id=factor_id,
            engine=engine,
            category=category,
            plan_item=item,
            config=config,
            metrics=metrics,
        )
        metrics_path = str(metrics_path_obj.relative_to(config.root))
        status = "ok"

    except NotImplementedError as exc:
        status = "error"
        reason = f"not_implemented: {exc}"
    except Exception as exc:  # pragma: no cover - 防禦性
        status = "error"
        reason = f"exception: {exc}"

    return FactorEvalItemResult(
        factor_id=factor_id,
        engine=engine,
        category=category,
        decided_action=decided_action,
        status=status,
        reason=reason,
        metrics_path=metrics_path,
        factor_path=factor_path,
        metrics=metrics,
    )


def _summarise_results(
    *,
    plan: FactorPlan,
    config: FactorEvalConfig,
    results: Iterable[FactorEvalItemResult],
) -> FactorEvalSummary:
    total = 0
    compute_and_eval = 0
    eval_only = 0
    skipped = 0
    failed = 0

    for r in results:
        total += 1
        if r.status == "skipped":
            skipped += 1
        elif r.status == "ok":
            if config.mode == "compute+eval":
                compute_and_eval += 1
            elif config.mode == "evalonly":
                eval_only += 1
        else:
            failed += 1

    return FactorEvalSummary(
        as_of_date=plan["as_of_date"],
        profile=config.profile,
        engine_kind=config.engine_kind,
        total=total,
        compute_and_eval=compute_and_eval,
        eval_only=eval_only,
        skipped=skipped,
        failed=failed,
    )


# ---------------------------------------------------------------------------
# Path helpers
# ---------------------------------------------------------------------------


def _factor_timeseries_output_path(root: Path, factor_id: str, as_of: date) -> Path:
    """
    Location to write factor parquet for a given factor_id and as_of date.

    Current convention:
    datahub/silver/alpha/factor/<factor_id>/yyyymm=YYYYMM/<factor_id>_YYYY-MM-DD.parquet
    """
    yyyymm = as_of.strftime("%Y%m")
    fname = f"{factor_id}_{as_of.isoformat()}.parquet"
    return (
        root
        / "datahub"
        / "silver"
        / "alpha"
        / "factor"
        / factor_id
        / f"yyyymm={yyyymm}"
        / fname
    )


def _factor_eval_output_path(root: Path, factor_id: str, as_of: date) -> Path:
    """
    Location to write factor_eval JSON for a given factor_id and as_of date.

    Convention:
    reports/factor_eval/<factor_id>_<YYYY-MM-DD>.json
    """
    fname = f"{factor_id}_{as_of.isoformat()}.json"
    return root / "reports" / "factor_eval" / fname


# ---------------------------------------------------------------------------
# Persistence helpers
# ---------------------------------------------------------------------------


def _write_factor_timeseries(df: pd.DataFrame, path: Path, overwrite: bool) -> None:
    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not overwrite:
        # Idempotent：預設不覆寫已存在檔案
        return
    df.to_parquet(path, index=True)


def load_factor_timeseries(path: str | Path) -> pd.DataFrame:
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(f"factor timeseries parquet not found: {p}")
    return pd.read_parquet(p)


def _write_factor_eval_json(
    *,
    path: Path,
    factor_id: str,
    engine: str,
    category: str,
    plan_item: FactorPlanItem,
    config: FactorEvalConfig,
    metrics: Dict[str, Any],
) -> None:
    path = path.resolve()
    path.parent.mkdir(parents=True, exist_ok=True)

    payload: Dict[str, Any] = {
        "factor_id": factor_id,
        "engine": engine,
        "category": category,
        "as_of_date": config.as_of_date.isoformat(),
        "profile": config.profile,
        "engine_kind": config.engine_kind,
        "wf_windows": config.wf_windows,
        "gate_rules": plan_item.get("gate_rules", {}),
        "metrics": metrics,
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "source": "factor_eval_lib",
        "plan_item": {
            # 精簡版 plan item，用來 debug / audit
            "decided_action": plan_item.get("decided_action"),
            "universe": plan_item.get("universe"),
            "data_freq": plan_item.get("data_freq"),
            "reasons": plan_item.get("reasons"),
        },
    }

    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2, sort_keys=True)


# ---------------------------------------------------------------------------
# Domain-specific hooks (to be implemented properly in later steps)
# ---------------------------------------------------------------------------


def compute_factor_timeseries(
    *,
    factor_id: str,
    item: FactorPlanItem,
    plan: FactorPlan,
    config: FactorEvalConfig,
) -> pd.DataFrame:
    """
    Compute factor timeseries for the given factor_id and as_of_date.

    This function is a *hook* and intentionally left unimplemented here because
    its behaviour is project-specific: it needs access to silver/alpha
    prices/chip/per/dividend, plus additional configuration for lookback windows,
    business-day calendars, etc.

    You are expected to implement this by delegating to your factor engine
    (for example a module like factor_engine_classic.py or similar).
    """
    raise NotImplementedError(
        f"compute_factor_timeseries is not implemented for factor_id={factor_id!r}. "
        "Wire this to your factor engine implementation."
    )


def compute_factor_metrics(
    *,
    factor_id: str,
    df: pd.DataFrame,
    item: FactorPlanItem,
    plan: FactorPlan,
    config: FactorEvalConfig,
) -> Dict[str, Any]:
    """
    Compute WF metrics (rank-IC, coverage, turnover, PSR, etc.) for a factor.

    This function is also a hook: factor_slo_lib / WFGate define what metrics are
    required, and this function should produce at least those keys so that
    downstream checks can be applied.

    Keeping this unimplemented by default avoids silently producing misleading
    numbers. Implementations should be deterministic and fully based on the
    data in `df` plus any required benchmark/returns data loaded via `config.root`.
    """
    raise NotImplementedError(
        f"compute_factor_metrics is not implemented for factor_id={factor_id!r}. "
        "Implement WF metrics consistent with factor_slo_lib and WFGate."
    )
